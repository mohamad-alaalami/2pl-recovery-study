def sha(x):
    return hashlib.sha256(np.ascontiguousarray(x).tobytes()).hexdigest()


GOLDEN_ARRAYS = Path(__file__).resolve().parent / "data" / "golden_s0_reference.npz"
FLOAT_TOL = 1e-12        # cross-platform: floating-point rounding (BLAS, libm) may differ in the last bits


class PortCheckTests(unittest.TestCase):
    """Reference datasets produced by the original implementation (generated on Windows x86-64).
    On that reference platform they are reproduced bit for bit. On other platforms the seeds and
    the response matrix Y must be identical and a, b, theta equal within FLOAT_TOL."""

    def test_reference_datasets_match_the_original_implementation(self):
        cfg = load_config(CONFIGS / "final_v1.yaml")
        ref = np.load(GOLDEN_ARRAYS)
        worst = {}
        for u in resolve(cfg, list(GOLDEN_S0)):
            sim = simulate_replicate(cfg, u.condition, u.replicate)
            self.assertEqual(sim["sampler_seed"], int(ref[f"{u.unit_id}|sampler_seed"]))
            np.testing.assert_array_equal(sim["Y"], ref[f"{u.unit_id}|Y"], err_msg=u.unit_id)
            for k in ("a", "b", "theta"):
                d = float(np.max(np.abs(sim[k] - ref[f"{u.unit_id}|{k}"])))
                worst[k] = max(worst.get(k, 0.0), d)
                self.assertLessEqual(d, FLOAT_TOL, f"{u.unit_id} {k}: max |diff| {d:.3e}")
        print(f"\n[port check] platform={sys.platform}; max |diff| vs reference: "
              + ", ".join(f"{k} {v:.3e}" for k, v in worst.items()))

    @unittest.skipUnless(sys.platform == "win32", "bit-identity is checked on the reference platform")
    def test_reference_datasets_are_bit_identical_on_the_reference_platform(self):
        cfg = load_config(CONFIGS / "final_v1.yaml")
        for u in resolve(cfg, list(GOLDEN_S0)):
            sim = simulate_replicate(cfg, u.condition, u.replicate)
            for k in ("a", "b", "theta", "Y"):
                self.assertEqual(sha(sim[k]), GOLDEN_S0[u.unit_id][k], f"{u.unit_id} {k}")
            self.assertEqual(sim["sampler_seed"], GOLDEN_S0[u.unit_id]["sampler_seed"])


class GeneratorTests(unittest.TestCase):
    def setUp(self):
        self.gen = load_config(CONFIGS / "final_v1.yaml")["item_generator"]

    def test_truncated_normal_centers(self):
        for tau in (0.10, 0.25, 0.75):
            exact = truncnorm.mean((0.65 - 1) / tau, (4.0 - 1) / tau, loc=1, scale=tau)
            self.assertAlmostEqual(truncated_normal_mean(1.0, tau, 0.65, 4.0), exact, places=10)
        self.assertAlmostEqual(truncated_normal_mean(0.0, 1.5, -4.5, 4.5), 0.0, places=12)

    def test_every_bank_hits_exact_sds_correlation_means_and_bounds(self):
        rng = np.random.default_rng(3)
        for world, (ta, tb) in WORLDS.items():
            for rho in (0.0, 0.3):
                for J in (25, 50):
                    ca = truncated_normal_mean(1.0, ta, 0.65, 4.0)
                    for _ in range(20):
                        a, b, tries = koenig2022_items(J, ta, tb, rho, self.gen, rng)
                        self.assertGreaterEqual(tries, 1)
                        self.assertAlmostEqual(a.std(ddof=1), ta, places=10)
                        self.assertAlmostEqual(b.std(ddof=1), tb, places=10)
                        self.assertAlmostEqual(np.corrcoef(a, b)[0, 1], rho, places=10)
                        self.assertAlmostEqual(a.mean(), ca, places=10)
                        self.assertAlmostEqual(b.mean(), 0.0, places=10)
                        self.assertTrue(np.all(a > 0.45) and np.all(a < 4.0))
                        self.assertTrue(np.all(b > -4.5) and np.all(b < 4.5))

    def test_impossible_bounds_fail_loudly(self):
        impossible = dict(self.gen, accept_alpha=[0.99, 1.01], max_tries=5)
        with self.assertRaises(RuntimeError):
            koenig2022_items(25, 0.75, 1.5, 0.0, impossible, np.random.default_rng(0))


class ResponseAndSeedTests(unittest.TestCase):
    def test_responses_follow_the_2pl(self):
        rng = np.random.default_rng(1)
        a, b = np.array([0.5, 1.0, 2.0]), np.array([-1.0, 0.0, 1.0])
        theta = rng.standard_normal(200_000)
        Y = simulate_responses(a, b, theta, rng)
        self.assertEqual(Y.shape, (200_000, 3))
        self.assertTrue(set(np.unique(Y)) <= {0, 1})
        expected = (1 / (1 + np.exp(-(a[None, :] * (theta[:, None] - b[None, :]))))).mean(axis=0)
        np.testing.assert_allclose(Y.mean(axis=0), expected, atol=0.004)
        self.assertGreater(Y[theta > 1].mean(), Y[theta < -1].mean())

    def test_determinism_common_items_across_N_and_replicates_differ(self):
        cfg = load_config(CONFIGS / "final_v1.yaml")
        units = {u.unit_id: u for u in enumerate_units(cfg, blocks=["S0_main"])}
        u50 = units["N50_J25_typical_rho0.3_full__r000"]
        u500 = units["N500_J25_typical_rho0.3_full__r000"]
        s1, s2 = (simulate_replicate(cfg, u50.condition, 0) for _ in range(2))
        for k in ("a", "b", "theta", "Y"):
            np.testing.assert_array_equal(s1[k], s2[k])
        s3 = simulate_replicate(cfg, u500.condition, 0)
        np.testing.assert_array_equal(s1["a"], s3["a"])                 # same items for every N
        np.testing.assert_array_equal(s1["b"], s3["b"])
        self.assertNotEqual(s1["sampler_seed"], s3["sampler_seed"])
        other = simulate_replicate(cfg, u50.condition, 1)
        self.assertFalse(np.array_equal(s1["a"], other["a"]))
        self.assertNotEqual(derive_seed(1, "x", 0), derive_seed(2, "x", 0))

    def test_order_independence(self):
        """A unit's data do not depend on which units were simulated before it."""
        cfg = load_config(CONFIGS / "final_v1.yaml")
        units = enumerate_units(cfg)
        pick = [units[i] for i in (17, 5000, 9000, 3, 7777)]
        first = [simulate_replicate(cfg, u.condition, u.replicate)["Y"] for u in pick]
        again = [simulate_replicate(cfg, u.condition, u.replicate)["Y"] for u in reversed(pick)]
        for x, y in zip(first, reversed(again)):
            np.testing.assert_array_equal(x, y)


